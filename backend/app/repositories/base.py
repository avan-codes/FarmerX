from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class StorageBackend(Protocol):
    """Every service depends on this, never on the filesystem.
    Swapping to SQLite/Postgres is a one-file change."""

    async def startup(self) -> None: ...
    async def read(self, collection: str, doc_id: str) -> dict[str, Any] | None: ...
    async def write(self, collection: str, doc_id: str, doc: dict[str, Any]) -> None: ...
    async def delete(self, collection: str, doc_id: str) -> bool: ...
    async def exists(self, collection: str, doc_id: str) -> bool: ...
    async def list(self, collection: str, *, filters: dict | None = None,
                   sort: list[tuple[str, str]] | None = None,
                   page: int = 1, page_size: int = 20) -> tuple[list[dict], int]: ...
    async def count(self, collection: str, *, filters: dict | None = None) -> int: ...
    async def next_ref(self, prefix: str) -> str: ...